"""Shared helpers for the PLACER seed package.

Everything the individual seed steps need to agree on lives here: stable
ObjectIds (so re-running is idempotent), the provenance flags stamped on every
synthetic document, the fixed local development credentials, the canonical
question categories, the PDF builder used for synthetic resumes, and small
reporting helpers.

No secrets are stored in this file. The seed password is a *local development*
credential that can be overridden with ``PLACER_SEED_PASSWORD``; the operator
guide generated by ``run_all.py`` is written outside git.
"""
from __future__ import annotations

import hashlib
import os
from datetime import datetime
from typing import Any

from bson import ObjectId
from motor.motor_asyncio import AsyncIOMotorDatabase

from app.core.security import hash_password
from app.models.user import AdminInDB, TPOInDB, UserInDB, UserRole
from app.repositories.profile_repositories import AdminRepository, TPORepository
from app.repositories.user_repository import UserRepository

# ---------------------------------------------------------------------------
# Identity / provenance
# ---------------------------------------------------------------------------
SEED_BATCH = "placer-seed-v2"
EMAIL_DOMAIN = "placer.edu"
SEED_PASSWORD = os.environ.get("PLACER_SEED_PASSWORD", "Placer@2026")

ADMIN_EMAIL = f"admin@{EMAIL_DOMAIN}"
TPO_EMAIL = f"tpo@{EMAIL_DOMAIN}"

SYNTHETIC: dict[str, Any] = {
    "data_origin": "synthetic",
    "is_synthetic": True,
    "synthetic_batch": SEED_BATCH,
}


def stable_oid(key: str) -> ObjectId:
    """Deterministic ObjectId so re-running never creates duplicates."""
    return ObjectId(hashlib.sha256(f"{SEED_BATCH}:{key}".encode("utf-8")).hexdigest()[:24])


def now() -> datetime:
    return datetime.utcnow()


# ---------------------------------------------------------------------------
# Question categories — exactly the categories the application already uses.
# ---------------------------------------------------------------------------
CATEGORY_NAMES: tuple[str, ...] = (
    "Data Structures & Algorithms",
    "DBMS & SQL",
    "Operating Systems",
    "Computer Networks",
    "Object-Oriented Programming",
    "Python Programming",
    "JavaScript & Web Development",
    "Aptitude & Logical Reasoning",
    "Machine Learning & AI",
    "Cybersecurity",
    "Cloud & DevOps",
    "Software Engineering",
    "Verbal Ability",
)


def category_id(name: str) -> ObjectId:
    return stable_oid(f"category:{name}")


async def ensure_categories(db: AsyncIOMotorDatabase) -> dict[str, str]:
    """Create the canonical categories and return ``{name: id}``."""
    result: dict[str, str] = {}
    for name in CATEGORY_NAMES:
        oid = category_id(name)
        existing = await db.question_categories.find_one({"_id": oid})
        if existing:
            result[name] = str(oid)
            continue
        # Defensive: if a legacy category with the same name exists under a
        # different id, reuse it rather than creating a duplicate.
        legacy = await db.question_categories.find_one(
            {"name": {"$regex": f"^{name}$", "$options": "i"}}
        )
        if legacy:
            result[name] = str(legacy["_id"])
            continue
        await db.question_categories.insert_one(
            {"_id": oid, "name": name, "parent_category_id": None, **SYNTHETIC}
        )
        result[name] = str(oid)
    return result


