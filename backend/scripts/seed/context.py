async def ensure_admin(db: AsyncIOMotorDatabase) -> tuple[UserInDB, AdminInDB]:
    users = UserRepository(db)
    admins = AdminRepository(db)
    user = await users.get_by_email(ADMIN_EMAIL)
    if not user:
        user = await users.create(
            {
                "email": ADMIN_EMAIL,
                "password_hash": hash_password(SEED_PASSWORD),
                "role": UserRole.ADMIN.value,
                "auth_provider": "local",
                "is_active": True,
                "created_at": now(),
                "last_login": None,
                **SYNTHETIC,
            }
        )
    profile = await admins.get_by_user_id(user.id)
    if not profile:
        profile = await admins.create(
            {
                "_id": stable_oid("admin-profile"),
                "user_id": user.id,
                "name": "Placement Administrator",
                **SYNTHETIC,
            }
        )
    return user, profile


